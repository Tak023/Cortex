/* ─────────────────────────── CLI ─────────────────────────── */

function scaffoldCli(
  appDir: string,
  concept: Concept,
  pkgName: string,
  files: string[],
) {
  write(
    appDir,
    "package.json",
    JSON.stringify(
      {
        name: pkgName,
        version: "0.1.0",
        private: true,
        type: "module",
        bin: { [pkgName]: "./bin/cli.mjs" },
        scripts: {
          start: "node ./bin/cli.mjs",
          dev: "node ./bin/cli.mjs",
          test: "node ./bin/cli.mjs help",
          build: "node -e \"console.log('cli build ok')\"",
        },
      },
      null,
      2,
    ) + "\n",
    files,
  );

  write(
    appDir,
    "bin/cli.mjs",
    `#!/usr/bin/env node
const args = process.argv.slice(2);
const cmd = args[0] ?? "help";

const concept = ${JSON.stringify(
      {
        title: concept.title,
        summary: concept.summary,
        features: concept.features ?? [],
      },
      null,
      2,
    )};

if (cmd === "help" || cmd === "--help" || cmd === "-h") {
  console.log(\`\${concept.title}

\${concept.summary}

Commands:
  help     Show this help
  info     Print concept features
  version  Print version
\`);
  process.exit(0);
}

if (cmd === "info") {
  console.log(concept.title);
  console.log(concept.summary);
  for (const f of concept.features) console.log(" -", f);
  process.exit(0);
}

if (cmd === "version") {
  console.log("0.1.0");
  process.exit(0);
}

console.error("Unknown command:", cmd);
process.exit(1);
`,
    files,
  );

  write(
    appDir,
    "README.md",
    `# ${concept.title}

\`\`\`bash
node bin/cli.mjs help
node bin/cli.mjs info
\`\`\`
`,
    files,
  );
}

/* ─────────────────────────── API ─────────────────────────── */

function scaffoldApi(
  appDir: string,
  concept: Concept,
  pkgName: string,
  files: string[],
) {
  write(
    appDir,
    "package.json",
    JSON.stringify(
      {
        name: pkgName,
        version: "0.1.0",
        private: true,
        type: "module",
        scripts: {
          dev: "node server.mjs",
          start: "node server.mjs",
          test: "node --check server.mjs",
          build: "node --check server.mjs",
        },
      },
      null,
      2,
    ) + "\n",
    files,
  );

  write(
    appDir,
    "server.mjs",
    `import http from "http";

const port = Number(process.env.PORT || 8787);
const concept = ${JSON.stringify({
      title: concept.title,
      summary: concept.summary,
      features: concept.features ?? [],
      stack: concept.stack ?? [],
    })};

const server = http.createServer((req, res) => {
  const url = new URL(req.url || "/", \`http://\${req.headers.host}\`);
  res.setHeader("content-type", "application/json; charset=utf-8");

  if (url.pathname === "/health") {
    res.end(JSON.stringify({ ok: true }));
    return;
  }
  if (url.pathname === "/api/concept") {
    res.end(JSON.stringify(concept, null, 2));
    return;
  }
  if (url.pathname === "/api/features") {
    res.end(JSON.stringify({ features: concept.features }, null, 2));
    return;
  }

  res.statusCode = 404;
  res.end(JSON.stringify({ error: "not found", paths: ["/health", "/api/concept", "/api/features"] }));
});

server.listen(port, "127.0.0.1", () => {
  console.log(\`API listening on http://127.0.0.1:\${port}\`);
});
`,
    files,
  );

  write(
    appDir,
    "README.md",
    `# ${concept.title}

\`\`\`bash
npm start
curl http://127.0.0.1:8787/api/concept
\`\`\`
`,
    files,
  );
}

function escapeJsx(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;");
}
