/**
 * Real app scaffolding — turns a Cortex concept into source code on disk.
 * Called during the Implementation pipeline phase.
 */
import fs from "fs";
import path from "path";
import { execFile } from "child_process";
import { promisify } from "util";
import type { Concept, Project } from "../types";
import { projectWorkspaceDir } from "../workspace";
import { detectKind } from "./detectKind";
import {
  childProjectInstallEnv,
  childProjectBuildEnv,
  NPM_INSTALL_ARGS,
} from "./childEnv";

const execFileAsync = promisify(execFile);

export type ScaffoldResult = {
  appDir: string;
  filesWritten: string[];
  installOk: boolean;
  installLog: string;
  /** True when next build (or cli/api smoke) succeeded after scaffold */
  buildOk?: boolean;
  buildLog?: string;
  runHint: string;
  summary: string;
};

function slugify(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "")
      .slice(0, 40) || "app"
  );
}

function write(root: string, rel: string, content: string, out: string[]) {
  const full = path.join(root, rel);
  fs.mkdirSync(path.dirname(full), { recursive: true });
  fs.writeFileSync(full, content, "utf-8");
  out.push(rel);
}

function copyTree(src: string, dest: string, out: string[], prefix = "") {
  if (!fs.existsSync(src)) return;
  for (const entry of fs.readdirSync(src, { withFileTypes: true })) {
    const s = path.join(src, entry.name);
    const rel = path.join(prefix, entry.name);
    const d = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      fs.mkdirSync(d, { recursive: true });
      copyTree(s, d, out, rel);
    } else {
      fs.mkdirSync(path.dirname(d), { recursive: true });
      fs.copyFileSync(s, d);
      out.push(rel.replace(/\\/g, "/"));
    }
  }
}

function dockerTemplateDir(): string {
  const candidates = [
    // Compiled-adjacent templates (works in Next server & tsx)
    path.join(__dirname, "templates", "docker"),
    // Dev mode: cwd is the project root
    path.join(process.cwd(), "src", "lib", "build", "templates", "docker"),
    // Packaged desktop: prepare-standalone.cjs stages templates/ at the
    // standalone root, and server.js chdirs there before starting
    path.join(process.cwd(), "templates", "docker"),
  ];
  // page.tsx must exist or the scaffolded app can't build — an empty or
  // partial template dir is as fatal as a missing one
  for (const c of candidates) {
    if (fs.existsSync(path.join(c, "app", "page.tsx"))) return c;
  }
  throw new Error(
    `Docker app template not found (looked in: ${candidates.join(", ")}). ` +
      `The packaged app must ship src/lib/build/templates via desktop-runtime/templates.`,
  );
}



/**
 * Scaffold a runnable application under `<workspace>/app`.
 */
export async function scaffoldAppFromConcept(
  project: Project,
  options: { runInstall?: boolean } = {},
): Promise<ScaffoldResult> {
  const workspace = projectWorkspaceDir(project);
  const appDir = path.join(workspace, "app");
  fs.mkdirSync(appDir, { recursive: true });

  const concept = project.concept;
  const kind = detectKind(concept, project.sharedMemory?.concept ?? "");
  const pkgName = slugify(concept.title);
  const files: string[] = [];

  if (kind === "docker") {
    scaffoldDockerViewer(appDir, concept, pkgName, files);
  } else if (kind === "cli") {
    scaffoldCli(appDir, concept, pkgName, files);
  } else if (kind === "api") {
    scaffoldApi(appDir, concept, pkgName, files);
  } else {
    scaffoldWebApp(appDir, concept, pkgName, files);
  }

  // Always write project meta for the generated app
  write(
    appDir,
    "CORTEX.md",
    `# Generated by Cortex

**Project:** ${project.name}  
**Concept:** ${concept.title}  
**Kind:** ${kind}  
**Generated:** ${new Date().toISOString()}

## Idea / concept
${concept.summary}

## Features
${(concept.features ?? []).map((f) => `- ${f}`).join("\n")}

## Stack
${(concept.stack ?? []).join(", ")}

## Pipeline context
This app was scaffolded during the **implementation** phase. Docs from earlier
phases live in \`../artifacts/\`.
`,
    files,
  );

  let installOk = false;
  let installLog = "skipped";
  let buildOk = false;
  let buildLog = "skipped";

  if (options.runInstall !== false && fs.existsSync(path.join(appDir, "package.json"))) {
    // Up to 2 install attempts — a partial node_modules breaks the build smoke
    for (let attempt = 1; attempt <= 2; attempt++) {
      try {
        const { stdout, stderr } = await execFileAsync(
          "npm",
          [...NPM_INSTALL_ARGS],
          {
            cwd: appDir,
            timeout: 240_000,
            env: childProjectInstallEnv(),
            maxBuffer: 8 * 1024 * 1024,
          },
        );
        installLog = `${stdout}\n${stderr}`.trim().slice(0, 2000) || "npm install ok";
        const needsNext = kind === "web" || kind === "docker";
        const nextPresent = fs.existsSync(
          path.join(appDir, "node_modules", "next", "package.json"),
        );
        const tsPresent = fs.existsSync(
          path.join(appDir, "node_modules", "typescript", "package.json"),
        );
        // Require typescript for Next TS apps (skipped when NODE_ENV=production)
        installOk = needsNext ? nextPresent && tsPresent : true;
        if (needsNext && nextPresent && !tsPresent) {
          installLog +=
            "\n[cortex] typescript missing (devDependency) — reinstall with --include=dev";
        }
        if (installOk) break;
        installLog += "\n[cortex] next missing after install — retrying clean";
        try {
          fs.rmSync(path.join(appDir, "node_modules"), {
            recursive: true,
            force: true,
          });
          fs.rmSync(path.join(appDir, "package-lock.json"), { force: true });
        } catch {
          /* ignore */
        }
      } catch (e) {
        installOk = false;
        installLog =
          e instanceof Error
            ? `${e.message}\n${(e as { stdout?: string; stderr?: string }).stderr ?? ""}`.slice(
                0,
                2000,
              )
            : String(e);
        try {
          fs.rmSync(path.join(appDir, "node_modules"), {
            recursive: true,
            force: true,
          });
        } catch {
          /* ignore */
        }
      }
    }

    // Build smoke for web/docker so Testing inherits a known-good tree
    if (installOk && (kind === "web" || kind === "docker")) {
      try {
        const { stdout, stderr } = await execFileAsync(
          "npx",
          ["--no-install", "next", "build"],
          {
            cwd: appDir,
            timeout: 300_000,
            env: childProjectBuildEnv(),
            maxBuffer: 8 * 1024 * 1024,
          },
        );
        buildOk = true;
        buildLog = `${stdout}\n${stderr}`.trim().slice(0, 2000) || "next build ok";
      } catch (e) {
        buildOk = false;
        buildLog =
          e instanceof Error
            ? `${e.message}\n${(e as { stdout?: string; stderr?: string }).stderr ?? ""}`.slice(
                0,
                2500,
              )
            : String(e);
        // Recovery: reinstall WITH devDependencies (Electron NODE_ENV=production skips them)
        if (
          /generate is not a function|next: command not found|TypeScript|typescript|required package/i.test(
            buildLog,
          )
        ) {
          try {
            fs.rmSync(path.join(appDir, "node_modules"), {
              recursive: true,
              force: true,
            });
            fs.rmSync(path.join(appDir, "package-lock.json"), { force: true });
            fs.rmSync(path.join(appDir, ".next"), {
              recursive: true,
              force: true,
            });
            await execFileAsync("npm", [...NPM_INSTALL_ARGS], {
              cwd: appDir,
              timeout: 240_000,
              env: childProjectInstallEnv(),
              maxBuffer: 8 * 1024 * 1024,
            });
            const retry = await execFileAsync(
              "npx",
              ["--no-install", "next", "build"],
              {
                cwd: appDir,
                timeout: 300_000,
                env: childProjectBuildEnv(),
                maxBuffer: 8 * 1024 * 1024,
              },
            );
            buildOk = true;
            buildLog =
              `recovered after clean reinstall (with devDependencies)\n${retry.stdout}\n${retry.stderr}`.slice(
                0,
                2000,
              );
            installOk = true;
          } catch (e2) {
            buildOk = false;
            buildLog +=
              "\n[recovery failed] " +
              (e2 instanceof Error ? e2.message : String(e2)).slice(0, 800);
          }
        }
      }
    } else if (kind === "cli" || kind === "api") {
      buildOk = installOk;
      buildLog = "n/a for cli/api";
    }
  }

  const runHint =
    kind === "cli"
      ? `cd "${appDir}" && npm start -- --help`
      : kind === "api"
        ? `cd "${appDir}" && npm run dev   # http://127.0.0.1:8787`
        : `cd "${appDir}" && npm run dev   # http://127.0.0.1:3456`;

  return {
    appDir,
    filesWritten: files,
    installOk,
    installLog,
    buildOk,
    buildLog,
    runHint,
    summary: `Scaffolded ${kind} app with ${files.length} files at ${appDir}` +
      (installOk ? " · install ✓" : " · install ✗") +
      (kind === "web" || kind === "docker"
        ? buildOk
          ? " · build ✓"
          : " · build ✗"
        : ""),
  };
}

/* ─────────────────────────── Docker viewer (matches user's idea) ─────────────────────────── */

function scaffoldDockerViewer(
  appDir: string,
  concept: Concept,
  pkgName: string,
  files: string[],
) {
  write(
    appDir,
    "package.json",
    JSON.stringify(
      {
        name: pkgName,
        version: "0.1.0",
        private: true,
        scripts: {
          dev: "npx next dev -H 127.0.0.1 -p 3456",
          build: "npx next build",
          start: "npx next start -H 127.0.0.1 -p 3456",
          test: "npx vitest run && npx playwright test",
          "test:unit": "npx vitest run",
          "test:e2e": "npx playwright test",
        },
        dependencies: {
          next: "15.2.4",
          react: "19.0.0",
          "react-dom": "19.0.0",
        },
        devDependencies: {
          "@types/node": "^20",
          "@types/react": "^19",
          "@types/react-dom": "^19",
          typescript: "^5",
        },
      },
      null,
      2,
    ) + "\n",
    files,
  );

  write(
    appDir,
    "tsconfig.json",
    JSON.stringify(
      {
        compilerOptions: {
          target: "ES2017",
          lib: ["dom", "dom.iterable", "esnext"],
          allowJs: true,
          skipLibCheck: true,
          strict: true,
          noEmit: true,
          esModuleInterop: true,
          module: "esnext",
          moduleResolution: "bundler",
          resolveJsonModule: true,
          isolatedModules: true,
          jsx: "preserve",
          incremental: true,
          plugins: [{ name: "next" }],
          paths: { "@/*": ["./*"] },
        },
        include: ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
        exclude: ["node_modules"],
      },
      null,
      2,
    ) + "\n",
    files,
  );

  write(
    appDir,
    "next.config.mjs",
    `/** @type {import('next').NextConfig} */
const nextConfig = {};
export default nextConfig;
`,
    files,
  );

  write(
    appDir,
    "next-env.d.ts",
    `/// <reference types="next" />
/// <reference types="next/image-types/global" />
`,
    files,
  );

  // Copy improved docker app sources (list + start/stop/restart + open Docker Desktop)
  const tpl = dockerTemplateDir();
  copyTree(path.join(tpl, "lib"), path.join(appDir, "lib"), files, "lib");
  copyTree(path.join(tpl, "app"), path.join(appDir, "app"), files, "app");

  write(
    appDir,
    "app/layout.tsx",
    `import type { Metadata } from "next";
import "./globals.css";

export const metadata: Metadata = {
  title: ${JSON.stringify(concept.title.slice(0, 60) || "Docker Viewer")},
  description: ${JSON.stringify(concept.summary.slice(0, 160))},
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html lang="en">
      <body>
        <div className="shell">
          <header className="top">
            <div>
              <div className="brand">${escapeJsx(concept.title.slice(0, 48) || "Docker Viewer")}</div>
              <div className="sub">Local Docker containers · generated by Cortex</div>
            </div>
          </header>
          <main>{children}</main>
        </div>
      </body>
    </html>
  );
}
`,
    files,
  );

  write(
    appDir,
    "README.md",
    `# ${concept.title}

${concept.summary}

## What Cortex built

A **local Docker container dashboard** (Next.js) that can:

- List all containers on this machine
- **Start / stop / restart** containers
- View logs + \`docker inspect\`
- Open Docker Desktop if the daemon is down

## Run

\`\`\`bash
cd app
npm install
npm run dev
\`\`\`

Open http://127.0.0.1:3456

## Requirements

- **Docker Desktop must be running** (whale icon steady in the menu bar)
- \`docker\` available on PATH

## Features from concept

${(concept.features ?? []).map((f) => `- ${f}`).join("\n")}
`,
    files,
  );
}

